// Conservative storage lease. Never acquire the GL mutex or wait for shader compilation.
// The GL thread publishes retirement after projectM actually releases its outgoing preset.
bool IsCustomPresetPackInUse(const std::string& directory) {
    if (directory.empty()) return false;
    const std::string prefix = "custom/" + directory.substr(directory.find_last_of('/') + 1) + "/";
    {
        std::lock_guard<std::mutex> lock(g_published.mutex);
        if (g_published.engineAlive) {
            if (g_library.CustomPackPending() || g_inputs.categoryDirty.load() ||
                g_inputs.categoryRequestedSerial.load() != g_inputs.categoryAppliedSerial.load()) return true;
            for (const auto* name : {&g_published.currentPreset, &g_published.outgoingPreset, &g_published.loadingPreset})
                if (name->compare(0, prefix.size(), prefix) == 0) return true;
        }
    }
    return g_prewarmer.UsesPresetPrefix(prefix);
}

// System-wide available memory (MemAvailable) in kB, or -1.
long MemInfoKb(const char* format) {
    FILE* f = fopen("/proc/meminfo", "r");
    if (!f) return -1;
    char line[128];
    long kb = -1;
    while (fgets(line, sizeof(line), f)) {
        if (sscanf(line, format, &kb) == 1) break;
    }
    fclose(f);
    return kb;
}

long AvailableMemoryKb() { return MemInfoKb("MemAvailable: %ld kB"); }

// Enables the texture pool while plenty of memory is free, else empties it (GL thread).
void UpdateTexturePool(double now) {
    static const long totalKb = MemInfoKb("MemTotal: %ld kB");
    long availableKb = AvailableMemoryKb();
    bool plenty = now >= g_prewarmPausedUntil.load() && totalKb > 0 && availableKb >= 0 &&
                  availableKb >= totalKb * kTexturePoolMinAvailableShare;
    size_t limit = plenty ? kTexturePoolBytes : 0;
    if (limit == g_engine.texturePoolLimit) return;
    projectm_opengl_set_texture_pool_limit(limit);
    g_engine.texturePoolLimit = limit;
    LOGI("Texture pool %s (%ld MB of %ld MB available)", limit ? "on" : "off", availableKb / 1024, totalKb / 1024);
}

// Whether the upcoming preset may be compiled in the background: its short-lived projectM instance
// must not push Android into taking memory from the music player.
bool PrewarmAllowed(double now) {
    if (!g_engine.prewarmerStarted) return false;  // Background compile is off
    if (now < g_prewarmPausedUntil.load()) return false;
    static const long totalKb = MemInfoKb("MemTotal: %ld kB");
    long availableKb = AvailableMemoryKb();
    if (totalKb > 0 && availableKb >= 0 && availableKb < totalKb * kPrewarmMinAvailableShare) {
        LOGW("PREWARM skipped: %ld MB of %ld MB available", availableKb / 1024, totalKb / 1024);
        return false;
    }
    return true;
}

// Resident memory of this process in kB, or -1.
long ResidentMemoryKb() {
    FILE* f = fopen("/proc/self/statm", "r");
    if (!f) return -1;
    long size = 0, resident = -1;
    if (fscanf(f, "%ld %ld", &size, &resident) != 2) resident = -1;
    fclose(f);
    return resident < 0 ? -1 : resident * (sysconf(_SC_PAGESIZE) / 1024);
}

// A preset's warp and composite shader code as tools/gen-preset-index.py reads it: the "warp_N=" and
// "comp_N=" lines without leading backticks, joined with newlines, /* */ and then // comments removed.
std::string ShaderCode(const std::string& preset) {
    std::string code;
    bool first = true;
    size_t pos = 0;
    while (pos < preset.size()) {
        size_t end = preset.find('\n', pos);
        if (end == std::string::npos) end = preset.size();
        size_t lineEnd = end > pos && preset[end - 1] == '\r' ? end - 1 : end;
        if (preset.compare(pos, 5, "warp_") == 0 || preset.compare(pos, 5, "comp_") == 0) {
            size_t eq = pos + 5;
            while (eq < lineEnd && isdigit(static_cast<unsigned char>(preset[eq]))) ++eq;
            if (eq > pos + 5 && eq < lineEnd && preset[eq] == '=') {
                size_t start = eq + 1;
                while (start < lineEnd && preset[start] == '`') ++start;
                if (!first) code += '\n';
                code.append(preset, start, lineEnd - start);
                first = false;
            }
        }
        pos = end + 1;
    }
    std::string withoutBlocks;
    for (size_t i = 0; i < code.size();) {
        size_t open = code.find("/*", i);
        size_t close = open == std::string::npos ? open : code.find("*/", open + 2);
        if (close == std::string::npos) {  // no (complete) block comment left
            withoutBlocks.append(code, i, std::string::npos);
            break;
        }
        withoutBlocks.append(code, i, open - i);
        i = close + 2;
    }
    std::string result;
    for (size_t i = 0; i < withoutBlocks.size();) {
        size_t comment = withoutBlocks.find("//", i);
        if (comment == std::string::npos) {
            result.append(withoutBlocks, i, std::string::npos);
            break;
        }
        result.append(withoutBlocks, i, comment - i);
        i = withoutBlocks.find('\n', comment);
        if (i == std::string::npos) break;
    }
    return result;
}

// Size of a preset's warp and composite shader code (bytes, without comments) and its number of
// for-loops: the suspected drivers of GPU compile memory, logged next to the measured memory.
// Counted like tools/gen-preset-index.py, so the log matches the weights in presets.idx.
void ShaderStats(const std::string& preset, size_t& bytes, int& loops) {
    std::string code = ShaderCode(preset);
    bytes = code.size();
    loops = 0;
    for (size_t f = code.find("for"); f != std::string::npos; f = code.find("for", f + 3)) {
        size_t after = f + 3;
        while (after < code.size() && isspace(static_cast<unsigned char>(code[after]))) ++after;
        bool word = f == 0 || !(isalnum(static_cast<unsigned char>(code[f - 1])) || code[f - 1] == '_');
        if (word && after < code.size() && code[after] == '(') ++loops;
    }
}

bool UseLightweight() {
    return g_inputs.transitionMode.load() == kTransitionLightweight;
}

// Sets projectM's window size to the surface size times `scale`. A change keeps the frames of the
// presets (scaled, projectM patch 0003), so it can happen at any frame.
void ApplyRenderScale(float scale) {
    if (!g_engine.pm || g_engine.width <= 0 || g_engine.height <= 0) return;
    const auto dimensions = projectmtv::RenderDimensionsFor(g_engine.width, g_engine.height, scale);
    const int width = dimensions.width;
    const int height = dimensions.height;
    if (width == g_engine.renderWidth && height == g_engine.renderHeight) return;
    projectm_set_window_size(g_engine.pm, width, height);
    g_engine.renderWidth = width;
    g_engine.renderHeight = height;
}

// The off-screen target for rendering below the surface size, (re)allocated for the given size.
bool EnsureScaledTarget(int width, int height) {
    if (g_engine.scaledFbo && g_engine.scaledWidth == width && g_engine.scaledHeight == height) return true;
    if (!g_engine.scaledFbo) glGenFramebuffers(1, &g_engine.scaledFbo);
    if (!g_engine.scaledTexture) glGenTextures(1, &g_engine.scaledTexture);
    glBindTexture(GL_TEXTURE_2D, g_engine.scaledTexture);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, width, height, 0, GL_RGBA, GL_UNSIGNED_BYTE, nullptr);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glBindTexture(GL_TEXTURE_2D, 0);
    glBindFramebuffer(GL_FRAMEBUFFER, g_engine.scaledFbo);
    glFramebufferTexture2D(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_TEXTURE_2D, g_engine.scaledTexture, 0);
    bool complete = glCheckFramebufferStatus(GL_FRAMEBUFFER) == GL_FRAMEBUFFER_COMPLETE;
    glBindFramebuffer(GL_FRAMEBUFFER, 0);
    g_engine.scaledWidth = complete ? width : 0;
    g_engine.scaledHeight = complete ? height : 0;
    if (!complete) LOGW("Scaled render target %dx%d unavailable", width, height);
    return complete;
}

// contextAlive: delete the GL objects (else they died with their context).
void ReleaseScaledTarget(bool contextAlive) {
    if (contextAlive) {
        if (g_engine.scaledFbo) glDeleteFramebuffers(1, &g_engine.scaledFbo);
        if (g_engine.scaledTexture) glDeleteTextures(1, &g_engine.scaledTexture);
    }
    g_engine.scaledFbo = g_engine.scaledTexture = 0;
    g_engine.scaledWidth = g_engine.scaledHeight = 0;
}

// Renders a frame at projectM's window size; below the surface size, into the off-screen target,
// stretched onto the surface by the GPU (one blit).
void RenderPresetFrame() {
    int width = g_engine.renderWidth;
    int height = g_engine.renderHeight;
    bool scaled = width != g_engine.width || height != g_engine.height;
    if (scaled && !EnsureScaledTarget(width, height)) {
        ApplyRenderScale(1.f);
        if (g_engine.renderWidth != g_engine.width || g_engine.renderHeight != g_engine.height) {
            LOGW("Capped render target unavailable: skipping frame without exceeding 1330");
            return;
        }
        scaled = false;
    }
    if (!scaled) {
        projectm_opengl_render_frame(g_engine.pm);
        return;
    }
    projectm_opengl_render_frame_fbo(g_engine.pm, g_engine.scaledFbo);
    glBindFramebuffer(GL_READ_FRAMEBUFFER, g_engine.scaledFbo);
    glBindFramebuffer(GL_DRAW_FRAMEBUFFER, 0);
    glBlitFramebuffer(0, 0, width, height, 0, 0, g_engine.width, g_engine.height, GL_COLOR_BUFFER_BIT, GL_LINEAR);
    glBindFramebuffer(GL_FRAMEBUFFER, 0);
    glViewport(0, 0, g_engine.width, g_engine.height);
}

// Loads one preset; returns false if it could not be loaded (and marks it as skipped).
bool LoadPreset(const std::string& name, bool smooth) {
    {
        std::lock_guard<std::mutex> lock(g_published.mutex);
        g_published.loadingPreset = name;
    }
    struct LoadingLease {
        ~LoadingLease() {
            std::lock_guard<std::mutex> lock(g_published.mutex);
            g_published.loadingPreset.clear();
        }
    } loadingLease;
    auto preset = g_library.ResolvePreset(name, true);
    const std::string& data = preset.data;
    if (data.empty()) {
        g_library.MarkSkipped(name, "unreadable or empty");
        return false;
    }
    g_engine.loading = name;
    g_engine.loadFailed = false;
    g_engine.inTransition = false;
    size_t shaderBytes = 0;
    int shaderLoops = 0;
    ShaderStats(data, shaderBytes, shaderLoops);
    long availBefore = AvailableMemoryKb();
    long rssBefore = ResidentMemoryKb();
    uint32_t cacheHitsBefore = 0, cacheMissesBefore = 0;
    projectm_opengl_program_cache_stats(&cacheHitsBefore, &cacheMissesBefore);
    UpdateTexturePool(NowSeconds());
    size_t poolBytes = projectm_opengl_texture_pool_bytes();
    double loadStart = NowSeconds();
    if (!g_engine.texturesApplied || g_engine.texturePaths != preset.texturePaths) {
        std::vector<const char*> paths;
        for (const auto& path : preset.texturePaths) paths.push_back(path.c_str());
        projectm_set_texture_search_paths(g_engine.pm, paths.data(), paths.size());
        g_engine.texturePaths = std::move(preset.texturePaths);
        g_engine.searchPathStorageLeases = preset.leases;
        g_engine.texturesApplied = true;
    }
    projectmtv::WriteTrail(projectmtv::kTrailRender, "loading '%s' (%s, %dx%d)", name.c_str(),
                           smooth ? "blend" : "cut", g_engine.renderWidth, g_engine.renderHeight);
    // Parses the preset, loads its textures and compiles its shaders: the stall at a switch, unless
    // the prewarmer already compiled them (then they come from the program cache).
    projectm_load_preset_data(g_engine.pm, data.c_str(), smooth);
    double loadEnd = NowSeconds();
    uint32_t cacheHits = 0, cacheMisses = 0;
    projectm_opengl_program_cache_stats(&cacheHits, &cacheMisses);
    projectmtv::WriteTrail(projectmtv::kTrailRender, "loaded '%s' (%s) in %.0f ms: %u programs cached, %u compiled",
                           name.c_str(), smooth ? "blend" : "cut", (loadEnd - loadStart) * 1000.0,
                           cacheHits - cacheHitsBefore, cacheMisses - cacheMissesBefore);
    double loadMs = (loadEnd - loadStart) * 1000.0;
    long availAfter = AvailableMemoryKb();
    long rssAfter = ResidentMemoryKb();
    // Memory the load took, to find the presets that cause memory peaks and calibrate their
    // weights: the drop in the system's available memory also covers GPU driver allocations.
    LOGI("LOAD preset='%s' ms=%.0f smooth=%d size=%dx%d weight_mb=%d shader_kb=%.1f loops=%d "
         "programs_cached=%u programs_compiled=%u pool_mb=%zu avail_drop_mb=%ld rss_growth_mb=%ld",
         name.c_str(), loadMs, smooth ? 1 : 0, g_engine.renderWidth, g_engine.renderHeight, g_library.Weight(name),
         shaderBytes / 1024.0, shaderLoops, cacheHits - cacheHitsBefore, cacheMisses - cacheMissesBefore,
         poolBytes / (1024 * 1024),
         availBefore >= 0 && availAfter >= 0 ? (availBefore - availAfter) / 1024 : 0,
         rssBefore >= 0 && rssAfter >= 0 ? (rssAfter - rssBefore) / 1024 : 0);
    if (g_engine.loadFailed) {
        g_library.MarkSkipped(name, "failed to load/compile");
        g_engine.loadFailed = false;
        return false;
    }
    g_engine.current = name;
    if (smooth) g_engine.outgoingStorageLeases = std::move(g_engine.currentStorageLeases);
    else g_engine.outgoingStorageLeases.clear();
    g_engine.currentStorageLeases = std::move(preset.leases);
    {
        std::lock_guard<std::mutex> lock(g_published.mutex);
        g_published.outgoingPreset = smooth ? g_published.currentPreset : std::string();
    }
    g_library.RecordShown(name);
    Publish(name);
    g_engine.lastLoadStart = loadStart;
    g_engine.lastLoadEnd = loadEnd;
    g_engine.lastLoadMs = loadMs;
    g_engine.detector.Arm(loadEnd, 2.0, name);
    // What the next switch will most likely load: the timer's next preset, and what Right (random)
    // and Left (previous) on the remote would pick. The previous one is usually still in the caches.
    if (PrewarmAllowed(loadEnd)) {
        g_prewarmer.Request({g_library.PeekNext(), g_library.PeekRandom(), g_library.PeekPrevious()});
    }
    return true;
}

// Measures the transition that follows the last load (see TrackTransition).
void BeginTransition(double seconds, bool lightweight) {
    g_engine.inTransition = true;
    g_engine.transitionLightweight = lightweight;
    g_engine.transitionStart = g_engine.lastLoadStart;
    g_engine.transitionLoadEnd = g_engine.lastLoadEnd;
    g_engine.transitionEnd = g_engine.lastLoadEnd + seconds;
    g_engine.transitionFrames = 0;
    g_engine.transitionSlowFrames = 0;
    g_engine.transitionCpuSeconds = 0;
    g_engine.transitionScaled = false;  // set by the caller for an Auto blend
    g_engine.transitionStepped = false;
    g_engine.transitionWorstMs = g_engine.lastLoadMs;
    g_engine.fpsBeforeTransition = g_engine.lastFps;
    g_engine.detector.Arm(g_engine.lastLoadEnd, seconds + 2.0, g_engine.current);  // judge it after the blend
}

// Switches using the given selector, retrying a few times when presets fail to load.
template <typename Selector>
bool SwitchPreset(Selector select, bool smooth) {
    // The new preset starts from the outgoing preset's stored frame, so the last frame must not
    // have gone straight to the screen. Every caller waits for a stored frame; this guards that.
    if (g_engine.lastFrameDirect) LOGW("Preset switch right after a direct frame: the new preset starts from an old image");
    for (int attempt = 0; attempt < kMaxLoadAttemptsPerFrame; ++attempt) {
        std::string name = select();
        if (name.empty()) return false;
        if (LoadPreset(name, smooth)) return true;
    }
    return false;
}

// Selector that tries `first` (if non-empty) and falls back to the shuffled order.
std::function<std::string()> FirstThenNext(std::string first) {
    return [first = std::move(first)]() mutable {
        if (!first.empty()) return std::exchange(first, std::string());
        return g_library.Next();
    };
}

// Automatic switch requested by projectM (preset time is up, or a hard cut on a loud beat).
void HandleAutoSwitch() {
    g_engine.switchRequested = false;
    bool hardCut = g_engine.switchHardCut || g_inputs.forceHardCut.exchange(false);
    int softCut = g_inputs.softCutDuration.load();
    bool lightweight = !hardCut && softCut > 0 && g_engine.snapshotReady && UseLightweight();
    bool smooth = !hardCut && !lightweight;
    // Auto blends run below the render size; the new preset starts at that size right away.
    bool scaled = smooth && softCut > 0 && g_inputs.transitionMode.load() == kTransitionAuto;
    g_engine.scaledUntil = 0;
    if (!lightweight) g_engine.fade.Stop();
    if (scaled) {
        g_engine.transitionScale = kBlendScales[g_engine.blendLevel];
        ApplyRenderScale(g_engine.transitionScale);
    }
    projectm_opengl_set_outgoing_preset_frame_divisor(g_engine.pm, scaled && g_engine.halfRateOutgoing ? 2 : 1);
    if (!SwitchPreset([] { return g_library.Next(); }, smooth)) {
        g_engine.fade.Stop();
        g_engine.scaledUntil = 0;
        return;
    }
    if (lightweight) {
        double seconds = std::min<double>(softCut, kMaxLightweightSeconds);
        g_engine.fade.Start(NowSeconds(), seconds);
        BeginTransition(seconds, true);
        projectmtv::WriteTrail(projectmtv::kTrailRender, "fading into '%s' (lightweight, %.0f s)",
                               g_engine.current.c_str(), seconds);
    } else if (smooth && softCut > 0) {
        BeginTransition(softCut, false);
        g_engine.transitionScaled = scaled;
        g_engine.transitionStepped = false;
        if (scaled) g_engine.scaledUntil = g_engine.transitionEnd + kScaledHoldSeconds;
        projectmtv::WriteTrail(projectmtv::kTrailRender, "blending into '%s' (%s, %d s, %dx%d)",
                               g_engine.current.c_str(), scaled ? "auto" : "classic", softCut,
                               g_engine.renderWidth, g_engine.renderHeight);
    }
}

void HandleCommands() {
    if (g_library.RestorePending()) return;
    if (g_inputs.categoryDirty.exchange(false)) {
        std::string requested;
        uint64_t serial;
        {
            std::lock_guard<std::mutex> lock(g_inputs.categoryMutex);
            requested = g_inputs.requestedCategory;
            serial = g_inputs.categoryRequestedSerial.load();
        }
        g_library.SetCategory(requested);
        uint64_t generation = g_library.CategoryGeneration();
        if (g_engine.categoryGeneration != generation) {
            g_engine.categoryGeneration = generation;
            g_engine.fade.Stop();
            g_engine.snapshotReady = false;
            g_engine.switchRequested = false;
            g_engine.scaledUntil = 0;
            g_inputs.command = kNone;
            // A category rebuild clears history. Record a retained preset first, so the next
            // candidates are prepared around the preset on screen, just as after a switch.
            if (g_library.Contains(g_engine.current)) g_library.RecordShown(g_engine.current);
            if (g_engine.prewarmerStarted)
                g_prewarmer.Request({g_library.PeekNext(), g_library.PeekRandom(), g_library.PeekPrevious()});
        }
        if (!g_library.Contains(g_engine.current) && !SwitchPreset([] { return g_library.Next(); }, false)) {
            g_inputs.categoryDirty = true; // continue bounded attempts on the next stored frame
            return;
        }
        g_inputs.categoryAppliedSerial = serial;
    }
    int command = g_inputs.command.exchange(kNone);
    if (command != kNone) {
        bool smooth = !g_inputs.commandHardCut.load();
        g_engine.fade.Stop();  // remote-control switches are immediate
        g_engine.scaledUntil = 0;
        projectm_opengl_set_outgoing_preset_frame_divisor(g_engine.pm, 1);
        switch (command) {
            case kNext:
                SwitchPreset([] { return g_library.Next(); }, smooth);
                break;
            case kRandom:
                SwitchPreset([] { return g_library.Random(g_engine.current); }, smooth);
                break;
            case kSkipCurrent:
                g_library.MarkSkipped(g_engine.current, "too slow on this device");
                SwitchPreset([] { return g_library.Next(); }, false);
                break;
            case kPrevious: {
                std::string previous = g_library.Previous();
                if (!previous.empty()) SwitchPreset(FirstThenNext(previous), smooth);
                break;
            }
            default:
                break;
        }
        g_engine.switchRequested = false;
    } else if (g_engine.switchRequested) {
        HandleAutoSwitch();
    }
    g_engine.snapshotReady = false;
}

// Called after a frame is complete: if projectM asked for a switch that will be a lightweight
// transition, keep a copy of this (outgoing) frame for the fade.
void CaptureOutgoingFrame() {
    if (g_engine.snapshotReady || !g_engine.switchRequested || g_engine.switchHardCut) return;
    if (g_inputs.forceHardCut.load() || g_inputs.softCutDuration.load() <= 0 || !UseLightweight()) return;
    if (g_inputs.command.load() != kNone) return;  // a remote-control switch comes first
    g_engine.snapshotReady = g_engine.fade.Capture(g_engine.width, g_engine.height);
}

void FeedAudio() {
    {
        std::lock_guard<std::mutex> lock(g_inputs.pcmMutex);
        g_engine.pcmScratch.swap(g_inputs.pcm);
        g_inputs.pcm.clear();
    }
    auto& pcm = g_engine.pcmScratch;
    if (pcm.empty()) return;
    size_t maxSamples = projectm_pcm_get_max_samples();
    size_t offset = pcm.size() > maxSamples ? pcm.size() - maxSamples : 0;
    projectm_pcm_add_uint8(g_engine.pm, pcm.data() + offset,
                           static_cast<unsigned int>(pcm.size() - offset), PROJECTM_MONO);
    pcm.clear();
}

void UpdateFps(double now) {
    ++g_engine.framesSinceFps;
    double elapsed = now - g_engine.fpsWindowStart;
    if (elapsed >= 1.0) {
        g_engine.lastFps = static_cast<float>(g_engine.framesSinceFps / elapsed);
        projectm_set_fps(g_engine.pm, static_cast<int32_t>(g_engine.lastFps + 0.5f));
        g_engine.framesSinceFps = 0;
        g_engine.fpsWindowStart = now;
    }
}

// Auto's blend resolution after a blend at `level` ran at blendFps (before: the fps before it).
void AdaptBlendLevel(float blendFps, float before, float cpuShare) {
    int level = g_engine.blendLevel;
    int percent = static_cast<int>(kBlendScales[level] * 100.f + 0.5f);
    if (blendFps < before * kBlendSlowRatio && cpuShare >= kCpuBoundShare) {
        g_engine.fastBlends = 0;
        if (!g_engine.halfRateOutgoing) {
            g_engine.halfRateOutgoing = true;
            LOGI("TRANSITION auto: blends are CPU-bound: the outgoing preset renders every 2nd frame");
        }
        if (level > 0) {
            // Whatever lowered it, the resolution was not what held this blend back.
            g_engine.blendLevelTooSlow[level - 1] = false;
            g_engine.blendLevel = level - 1;
            LOGI("TRANSITION auto: blend at %d%% ran at %.1f fps (%.1f before) on the CPU (%.0f%%): resolution "
                 "does not help, next blends at %d%%", percent, blendFps, before, cpuShare * 100.f,
                 static_cast<int>(kBlendScales[level - 1] * 100.f + 0.5f));
        }
    } else if (blendFps < before * kBlendSlowRatio) {
        g_engine.blendLevelTooSlow[level] = true;
        g_engine.fastBlends = 0;
        if (level + 1 < kBlendLevels && !g_engine.transitionStepped) {
            g_engine.blendLevel = level + 1;
            LOGI("TRANSITION auto: blend at %d%% ran at %.1f fps (%.1f before): next blends at %d%%", percent,
                 blendFps, before, static_cast<int>(kBlendScales[level + 1] * 100.f + 0.5f));
        }
    } else if (blendFps >= before * kBlendFastRatio) {
        // One heavy preset must not cap the resolution for the rest of the session.
        if (g_engine.fastBlends + 1 >= 2 * kFastBlendsToRaise && level > 0) g_engine.blendLevelTooSlow[level - 1] = false;
        if (++g_engine.fastBlends >= kFastBlendsToRaise && level > 0 && !g_engine.blendLevelTooSlow[level - 1]) {
            g_engine.blendLevel = level - 1;
            g_engine.fastBlends = 0;
            LOGI("TRANSITION auto: %d blends at %d%% kept up: next blends at %d%%", kFastBlendsToRaise, percent,
                 static_cast<int>(kBlendScales[level - 1] * 100.f + 0.5f));
        }
    } else {
        g_engine.fastBlends = 0;
    }
    g_published.blendScalePercent = static_cast<int>(kBlendScales[g_engine.blendLevel] * 100.f + 0.5f);
}

// Frame-time statistics for the running transition; logged and published when it ends. Auto blends
// adapt their resolution: once early in a blend that starts far too slow, and after each blend.
void TrackTransition(double now, double frameCpuSeconds) {
    double frameMs = g_engine.lastFrameAt > 0 ? (now - g_engine.lastFrameAt) * 1000.0 : 0;
    g_engine.lastFrameAt = now;
    if (!g_engine.inTransition) return;
    ++g_engine.transitionFrames;
    if (frameMs > 50.0) ++g_engine.transitionSlowFrames;  // below 20 fps: a visible stutter
    g_engine.transitionWorstMs = std::max(g_engine.transitionWorstMs, frameMs);
    double blending = now - g_engine.transitionLoadEnd;
    if (g_engine.transitionFrames > 1) g_engine.transitionCpuSeconds += frameCpuSeconds;  // not the load frame
    if (g_engine.transitionScaled && !g_engine.transitionStepped && g_engine.transitionFrames >= 15 &&
        blending >= 0.4 && g_engine.blendLevel + 1 < kBlendLevels && g_engine.fpsBeforeTransition > 0 &&
        g_engine.transitionFrames / blending < g_engine.fpsBeforeTransition * kBlendEarlySlowRatio &&
        g_engine.transitionCpuSeconds / blending < kCpuBoundShare) {
        g_engine.blendLevelTooSlow[g_engine.blendLevel] = true;
        ++g_engine.blendLevel;
        g_engine.transitionStepped = true;
        g_engine.transitionScale = kBlendScales[g_engine.blendLevel];
        LOGI("TRANSITION auto: blend at %.1f fps (%.1f before), lowering it to %d%% now",
             g_engine.transitionFrames / blending, g_engine.fpsBeforeTransition,
             static_cast<int>(g_engine.transitionScale * 100.f + 0.5f));
    }
    if (g_engine.transitionScaled && !g_engine.halfRateOutgoing && g_engine.transitionFrames >= 15 &&
        blending >= 0.4 && g_engine.fpsBeforeTransition > 0 &&
        g_engine.transitionFrames / blending < g_engine.fpsBeforeTransition * kBlendSlowRatio &&
        g_engine.transitionCpuSeconds / blending >= kCpuBoundShare) {
        g_engine.halfRateOutgoing = true;
        projectm_opengl_set_outgoing_preset_frame_divisor(g_engine.pm, 2);
        LOGI("TRANSITION auto: blend at %.1f fps (%.1f before) on the CPU: the outgoing preset renders every "
             "2nd frame from now on", g_engine.transitionFrames / blending, g_engine.fpsBeforeTransition);
    }
    if (now < g_engine.transitionEnd) return;
    g_engine.inTransition = false;
    projectmtv::WriteTrail(projectmtv::kTrailRender, "showing '%s' (transition done)", g_engine.current.c_str());
    float fps = static_cast<float>(g_engine.transitionFrames / std::max(0.001, now - g_engine.transitionStart));
    float blendFps = static_cast<float>(g_engine.transitionFrames / std::max(0.001, now - g_engine.transitionLoadEnd));
    bool lightweight = g_engine.transitionLightweight;
    float cpuShare = static_cast<float>(g_engine.transitionCpuSeconds / std::max(0.001, now - g_engine.transitionLoadEnd));
    LOGI("TRANSITION preset='%s' mode=%s scale=%d%% load_ms=%.0f fps=%.1f blend_fps=%.1f before_fps=%.1f "
         "cpu=%.0f%% outgoing_rate=1/%d frames=%d slow_frames=%d worst_ms=%.0f",
         g_engine.current.c_str(), lightweight ? "lightweight" : "classic",
         g_engine.transitionScaled ? static_cast<int>(g_engine.transitionScale * 100.f + 0.5f) : 100,
         g_engine.lastLoadMs, fps, blendFps, g_engine.fpsBeforeTransition, cpuShare * 100.f,
         g_engine.transitionScaled && g_engine.halfRateOutgoing ? 2 : 1, g_engine.transitionFrames, g_engine.transitionSlowFrames, g_engine.transitionWorstMs);
    g_published.lastTransitionFps = fps;
    g_published.transitionCounter.fetch_add(1);
    float before = g_engine.fpsBeforeTransition;
    if (g_engine.transitionScaled && before > 0) AdaptBlendLevel(blendFps, before, cpuShare);
    g_engine.transitionScaled = false;
}

// GL thread: applies Settings › Advanced › Shader binary cache. Turning it off waits for binary calls
// the prewarm thread has under way, so this must never run on the UI thread.
void ApplyProgramCache() {
    static bool applied = true;  // projectM's default
    bool enabled = g_inputs.programCache.load();
    if (enabled == applied) return;
    projectm_opengl_set_program_cache_enabled(enabled);
    projectmtv::TrailCacheOn() = enabled;
    applied = enabled;
    LOGI("Shader binary cache %s", enabled ? "on" : "off");
}

void StartPrewarmer() {
    g_prewarmer.Start([](const std::string& name) { return g_library.ResolvePreset(name); });
    g_engine.prewarmerStarted = true;  // the trail's compile= follows the worker itself (preset_prewarm.cpp)
}

// GL thread, once presets are showing: starts or stops the background compile thread (and with it
// its second EGL context) to follow Settings › Advanced › Background compile.
void ApplyBackgroundCompile() {
    if (g_engine.current.empty()) return;  // started with the first preset
    bool enabled = g_inputs.backgroundCompile.load();
    if (enabled == g_engine.prewarmerStarted) return;
    if (enabled) {
        StartPrewarmer();
        if (PrewarmAllowed(NowSeconds()))
            g_prewarmer.Request({g_library.PeekNext(), g_library.PeekRandom(), g_library.PeekPrevious()});
    } else {
        g_prewarmer.Stop();  // waits for a compile in progress
        g_engine.prewarmerStarted = false;
        projectmtv::TrailCompileOn() = false;
        projectmtv::WriteTrail(projectmtv::kTrailPrewarm, "background compile off");
    }
    LOGI("PREWARM background compile %s", enabled ? "on" : "off");
}

// contextAlive: the EGL context that owns our GL objects is still current (else just forget them).
void DestroyEngineLocked(bool contextAlive) {
    {
        std::lock_guard<std::mutex> lock(g_renderBudgetMutex);
        // The managed request belongs to the destroyed renderer/context. Legacy renderers
        // must not inherit its guard or tuple; a new managed renderer requests fresh review.
        const jlong generation = g_renderBudget.generation + 1;
        g_renderBudget = {};
        g_renderBudget.generation = generation; // Reject asynchronous callbacks from the old owner.
    }
    g_prewarmer.Stop();
    g_engine.prewarmerStarted = false;
    projectmtv::TrailCompileOn() = false;
    ReleaseScaledTarget(contextAlive);
    // The presets destroyed below may still add their textures to the pool: empty it afterwards.
    struct PoolRelease {
        bool contextAlive;
        ~PoolRelease() {
            if (contextAlive) projectm_opengl_set_texture_pool_limit(0);
            else projectm_opengl_forget_texture_pool();
            g_engine.texturePoolLimit = 0;
        }
    } poolRelease{contextAlive};
    if (contextAlive) {
        g_engine.fade.Release();
        g_engine.detector.Release();
    } else {
        g_engine.fade.Forget();
        g_engine.detector.Forget();
    }
    g_engine.snapshotReady = false;
    if (g_engine.pm) {
        projectm_destroy(g_engine.pm);
        g_engine.pm = nullptr;
    }
    {
        std::lock_guard<std::mutex> lock(g_published.mutex);
        g_published.engineAlive = false;
        g_published.outgoingPreset.clear();
        g_published.loadingPreset.clear();
    }
    g_engine.width = g_engine.height = 0;
    g_engine.renderWidth = g_engine.renderHeight = 0;
    g_engine.scaledUntil = 0;
    g_engine.transitionScaled = false;
    g_engine.appliedMeshWidth = g_engine.appliedMeshHeight = 0;
    g_engine.texturesApplied = false;
    g_engine.texturePaths.clear();
    g_engine.currentStorageLeases.clear();
    g_engine.outgoingStorageLeases.clear();
    g_engine.searchPathStorageLeases.clear();
    g_engine.inTransition = false;
    g_engine.lastFrameAt = 0;
    g_engine.current.clear();  // the next instance resumes from g_published.currentPreset
    g_engine.switchRequested = false;
    g_engine.lastFrameDirect = false;
    g_engine.blankSwitchPending = false;
    g_engine.detector.Disarm();
    g_engine.appliedNativeTrails = -1;
    {
        std::lock_guard<std::mutex> lock(g_published.mutex);
        g_published.nativeTrailsLevel = -1;
        g_published.nativeTrailsScale = -1;
        g_published.renderBudgetCompletedGeneration = -1;
    }
}

